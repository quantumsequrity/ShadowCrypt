//! Stealth System: sneaking, detection mechanics, backstab bonuses, and noise levels
//!
//! This module provides a comprehensive stealth system for the ShadowCrypt roguelike,
//! enabling tactical gameplay through sneaking, enemy awareness, and surprise attacks.
//!
//! # Features
//!
//! - **Sneaking**: Players can enter stealth mode to avoid detection
//! - **Detection**: Enemies have awareness levels and detection ranges
//! - **Noise**: Actions generate noise that can alert enemies
//! - **Backstab**: Attacking unaware enemies deals bonus damage
//! - **Environmental Factors**: Terrain and lighting affect stealth

use serde::{Deserialize, Serialize};
use std::collections::HashMap;

use crate::combat::StatusEffect;
