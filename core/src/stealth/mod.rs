use crate::world::Tile;

/// Light level affecting visibility and stealth
#[derive(Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Debug, Default)]
pub enum LightLevel {
    /// Complete darkness - excellent for stealth
    Dark,
    /// Dim lighting - good for stealth
    Dim,
    /// Normal dungeon lighting
    #[default]
    Normal,
    /// Bright lighting - poor for stealth
    Bright,
}

impl LightLevel {
    /// Returns the stealth modifier for this light level
    /// Higher values make stealth easier (reduce detection chance)
    pub fn stealth_modifier(&self) -> f32 {
        match self {
            Self::Dark => 0.4,   // 60% harder to detect
            Self::Dim => 0.7,    // 30% harder to detect
            Self::Normal => 1.0, // No modifier
            Self::Bright => 1.5, // 50% easier to detect
        }
    }

    /// Returns a color index for UI rendering
    pub fn color_index(&self) -> u8 {
        match self {
            Self::Dark => 0,    // DarkGrey
            Self::Dim => 1,     // Grey
            Self::Normal => 2,  // White
            Self::Bright => 11, // Yellow
        }
    }

    /// Returns the display name
    pub fn name(&self) -> &'static str {
        match self {
            Self::Dark => "Dark",
            Self::Dim => "Dim",
            Self::Normal => "Normal",
            Self::Bright => "Bright",
        }
    }
}

/// Noise level generated by various actions
