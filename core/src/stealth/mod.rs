/// Enemy awareness state
#[derive(Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Debug, Default)]
pub enum AwarenessState {
    /// Enemy is completely unaware of the player
    #[default]
    Unaware,
    /// Enemy heard something suspicious
    Suspicious,
    /// Enemy is searching for something
    Searching,
    /// Enemy is alert and actively looking
    Alert,
    /// Enemy has spotted the player
    Aware,
    /// Enemy is in active combat
    Combat,
}

impl AwarenessState {
    /// Returns the display name
    pub fn name(&self) -> &'static str {
        match self {
            Self::Unaware => "Unaware",
            Self::Suspicious => "Suspicious",
            Self::Searching => "Searching",
            Self::Alert => "Alert",
            Self::Aware => "Aware",
            Self::Combat => "Combat",
        }
    }

    /// Returns a color index for UI rendering
    pub fn color_index(&self) -> u8 {
        match self {
            Self::Unaware => 1,    // Grey
            Self::Suspicious => 11, // Yellow
            Self::Searching => 12,  // DarkYellow
            Self::Alert => 3,       // Red
            Self::Aware => 4,       // DarkRed
            Self::Combat => 3,      // Red
        }
    }

    /// Returns whether the enemy can perform backstab detection
    pub fn can_be_backstabbed(&self) -> bool {
        matches!(self, Self::Unaware | Self::Suspicious)
    }

    /// Returns the detection range modifier
    /// Lower values reduce enemy detection range
    pub fn detection_modifier(&self) -> f32 {
        match self {
            Self::Unaware => 0.5,
            Self::Suspicious => 0.75,
            Self::Searching => 1.0,
            Self::Alert => 1.25,
            Self::Aware => 1.5,
            Self::Combat => 1.5,
        }
    }

    /// Returns the next awareness state when detecting noise
    pub fn on_noise_detected(&self) -> Self {
        match self {
            Self::Unaware => Self::Suspicious,
            Self::Suspicious => Self::Searching,
            Self::Searching => Self::Alert,
            Self::Alert => Self::Alert,
            Self::Aware => Self::Aware,
            Self::Combat => Self::Combat,
        }
    }

    /// Returns the next awareness state on visual detection
    pub fn on_visual_detection(&self) -> Self {
        Self::Aware
    }

    /// Returns the state to decay to over time
    pub fn decay(&self) -> Self {
        match self {
            Self::Combat => Self::Alert,
            Self::Aware => Self::Alert,
            Self::Alert => Self::Searching,
            Self::Searching => Self::Suspicious,
            Self::Suspicious => Self::Unaware,
            Self::Unaware => Self::Unaware,
        }
    }
}

